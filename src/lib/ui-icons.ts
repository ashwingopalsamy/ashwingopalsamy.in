export type IconName = keyof typeof uiIcons;

interface IconOptions {
  size?: number;
  strokeWidth?: number;
  className?: string;
  label?: string;
}

const escapeAttribute = (value: string | number) =>
  String(value)
    .replaceAll("&", "&amp;")
    .replaceAll('"', "&quot;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");

export function iconMarkup(name: IconName, options: IconOptions = {}): string {
  const size = options.size ?? 16;
  const strokeWidth = options.strokeWidth ?? 1.8;
  const className = ["ui-icon", options.className].filter(Boolean).join(" ");
  const accessibility = options.label
    ? `role="img" aria-label="${escapeAttribute(options.label)}"`
    : 'aria-hidden="true"';
  const children = uiIcons[name]
    .map(([tag, attrs]) => {
      const serialized = Object.entries(attrs)
        .filter((entry): entry is [string, string | number] => entry[1] !== undefined)
        .map(([key, value]) => `${key}="${escapeAttribute(value)}"`)
        .join(" ");
      return `<${tag}${serialized ? ` ${serialized}` : ""}></${tag}>`;
    })
    .join("");

  return `<svg class="${escapeAttribute(className)}" viewBox="0 0 24 24" width="${size}" height="${size}" fill="none" stroke="currentColor" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round" ${accessibility}>${children}</svg>`;
}
